import assert from 'node:assert/strict';
import { CELL, Terrain } from '../../src/game/Terrain';
import { BlockWorld } from '../../src/game/blocks/BlockWorld';
import { BLOCKS, BLOCK_BY_ID, miningResult } from '../../src/game/blocks/BlockRegistry';
import { MiningAction, raycastBlocks } from '../../src/game/blocks/BlockInteraction';

const terrain=new Terrain(32,true);
terrain.top=new Float32Array(32*32).fill(6);
terrain.tileNames=['grass','sand'];
terrain.cell[1]=CELL.liquid;
terrain.cell[2]=CELL.solid;
const world=new BlockWorld(terrain);
const p={x:15,y:5,z:15};
assert.equal(BLOCK_BY_ID.size,BLOCKS.length,'block IDs must be unique');
assert.equal(world.get(p),'grass');
assert.equal(world.get({...p,y:2}),'dirt');
assert.equal(world.get({...p,y:0}),'stone');
assert.equal(world.place(p,'stone'),false,'cannot place into a filled voxel');
assert.equal(world.remove(p),'grass');
assert.equal(world.get(p),null);
assert.deepEqual(new Set(world.takeDirtyChunks()),new Set(['0,0','1,0','0,1']));
assert.equal(world.place(p,'stone'),true);
assert.equal(world.get(p),'stone');
assert.equal(world.place({...p,y:6},'not-a-block'),false);
assert.equal(world.place({x:1,y:6,z:0},'stone'),false,'protect water');
assert.equal(world.remove({x:2,y:5,z:0}),null,'protect trunks/obstacles');
assert.equal(world.remove({x:-1,y:0,z:0}),null);
assert.equal(world.place({x:0,y:256,z:0},'stone'),false);
const saved=JSON.parse(JSON.stringify(world.serialize()));
const reloaded=new BlockWorld(terrain);
assert.equal(reloaded.load(saved),true);
assert.equal(reloaded.get(p),'stone');
const before=JSON.stringify(reloaded.serialize());
assert.equal(reloaded.load({version:1,edits:[{x:0,y:6,z:0,id:'stone'},{x:-1,y:1,z:0,id:'stone'}]}),false);
assert.equal(JSON.stringify(reloaded.serialize()),before,'invalid payload must not partly apply');
assert.equal(reloaded.load({version:1,edits:[{...p,id:null},{...p,id:'stone'}]}),false,'duplicate coordinates are rejected');
assert.equal(reloaded.remove(p),'stone');
assert.equal(reloaded.place(p,'grass'),true);
assert.deepEqual(reloaded.serialize().edits,[],'restoring original removes its delta');
const ore=BLOCK_BY_ID.get('diamond_ore')!;
assert.equal(miningResult(ore,null).drop,null);
assert.equal(miningResult(ore,{kind:'pickaxe',tier:1,speed:1,durability:10}).drop,null);
assert.equal(miningResult(ore,{kind:'pickaxe',tier:3,speed:2,durability:10}).drop,'diamond_ore');
assert.equal(miningResult(ore,{kind:'pickaxe',tier:3,speed:2,durability:10}).seconds,1);
assert.equal(miningResult(ore,{kind:'pickaxe',tier:3,speed:2,durability:0}).drop,null);
assert.equal(world.remove(p),'stone');
assert.equal(world.place(p,'grass'),true);
const hit=raycastBlocks(world,{x:15.5,y:9,z:15.5},{x:0,y:-1,z:0},5);
assert.deepEqual(hit?.pos,p);
assert.deepEqual(hit?.normal,{x:0,y:1,z:0});
assert.equal(hit?.distance,3);
assert.equal(raycastBlocks(world,{x:15.5,y:9,z:15.5},{x:0,y:-1,z:0},2),null);
assert.equal(raycastBlocks(world,{x:15.5,y:9,z:15.5},{x:0,y:0,z:0},5),null);
const action=new MiningAction();
assert.equal(action.advance(world,p,null,.4).progress,.5);
action.cancel();assert.equal(action.progress,0);
assert.equal(action.advance(world,p,null,.8).broken,'grass');
assert.equal(world.get(p),null);
console.log('Block registry and sparse block world: OK');
const fractional=new Terrain(4,true);
fractional.top=new Float32Array(16).fill(2.25);fractional.tileNames=['grass'];
const physical=new BlockWorld(fractional);
assert.equal(physical.support(1.5,1.5,2.25),2.25);
assert.equal(physical.intersects({x:1.1,y:2.25,z:1.1},{x:1.9,y:3.9,z:1.9}),false);
assert.equal(physical.intersects({x:1.1,y:2.2,z:1.1},{x:1.9,y:3.9,z:1.9}),true);
assert.equal(physical.place({x:1,y:5,z:1},'stone'),true);
assert.equal(physical.support(1.5,1.5,4),2.25,'roof above the player is not support');
assert.equal(physical.support(1.5,1.5,6),6);
assert.equal(physical.remove({x:1,y:2,z:1}),'grass');
assert.equal(physical.support(1.5,1.5,2.25),2);
console.log('Voxel collision queries: OK');
